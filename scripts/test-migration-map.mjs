import assert from "node:assert/strict";
import { generateMap, moduleFor, targetFor, validatePlan } from "./map-migration.mjs";
const plan = { schemaVersion: 1, workstreams: [{ id: "core", title: "Core", gates: ["behavior"], dependsOn: [] }], rules: [{ pattern: ".*", workstream: "core" }] };
const row = { path: "core/backend/src/services/secret/service.ts", kind: "product-code", git_blob: "a".repeat(40), review_status: "unread" };
const output = generateMap(plan, [row, { ...row, path: "leftover/archive.md", kind: "archive" }]);
assert.equal(output.summary.mappedFiles, 1);
assert.equal(generateMap(plan, [{ ...row, path: "docs/capabilities/generated/catalog.json" }]).summary.mappedFiles, 0);
assert.ok(output.modules.endsWith("\t0\tunassessed\n"));
assert.equal(moduleFor(row.path), "core/backend/src/services/secret");
assert.equal(targetFor(row.path), "Go-domain-migration");
assert.equal(targetFor("core/frontend/src/pages/index.tsx"), "React-TypeScript");
assert.equal(targetFor("core/wasm/ironrdp-decoder/src/lib.rs"), "Rust-WASM");
assert.throws(() => validatePlan({ ...plan, workstreams: [{ ...plan.workstreams[0], dependsOn: ["core"] }] }), /Cyclic/);
assert.throws(() => validatePlan({ ...plan, workstreams: [{ ...plan.workstreams[0], dependsOn: ["missing"] }] }), /Unknown dependency/);
assert.throws(() => generateMap({ ...plan, rules: [] }, [row]), /Unmapped/);
assert.throws(() => generateMap(plan, [row, row]), /Duplicate/);
assert.throws(() => validatePlan({ ...plan, workstreams: [...plan.workstreams, plan.workstreams[0]] }), /Duplicate/);
assert.throws(() => validatePlan({ ...plan, rules: [{ pattern: ".*", workstream: "missing" }] }), /Unknown rule/);
assert.notEqual(output.modules, generateMap(plan, [{ ...row, git_blob: "b".repeat(40) }]).modules);
console.log("Migration map checks passed: coverage, cycles, unknown domains, duplicates, source drift and unassessed status.");
