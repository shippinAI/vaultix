// Renders the Vaultix table namespaces (docs/0119) from scripts/lib/table-namespaces.mjs.
//
//   --initialize  one time: read the inherited names from TableName, write the frozen map,
//                 the runtime rename list, and rewrite TableName to the vx_ names
//   --check       the frozen map follows the rules, and TableName and the rename list match it
//
// The frozen map is the history: it records which inherited name became which vx_ name and
// never loses a row, so upgrades from any earlier store keep working.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { namespaceTables, RAW_LEGACY_TABLES, TABLE_GROUPS, TABLE_PREFIX } from "./lib/table-namespaces.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mode = process.argv[2];
assert.ok(["--initialize", "--render", "--check"].includes(mode), "Usage: node scripts/map-table-namespaces.mjs --initialize|--render|--check");

const modelsPath = resolve(root, "core/backend/src/db/schemas/models.ts");
const mapPath = resolve(root, "docs/schema/table-namespaces.json");
const renamesPath = resolve(root, "core/backend/src/db/table-namespaces.ts");

const read = path => readFileSync(path, "utf8").replace(/^﻿/, "");
const enumRange = text => {
  const start = text.indexOf("export enum TableName {");
  assert.ok(start >= 0, "TableName enum not found");
  return [start, text.indexOf("\n}", start) + 2];
};
const enumEntries = text => {
  const [start, end] = enumRange(text);
  return [...text.slice(start, end).matchAll(/^(\s+)([A-Za-z0-9]+)\s*=\s*"([^"]+)"(,?)/gm)].map(m => ({ key: m[2], value: m[3] }));
};

// "enum" tables are named through TableName, so code and migrations already use the vx_ name;
// "raw" tables are created under their inherited name by historical raw-SQL migrations.
const renderRenames = rows => {
  const pairs = rows.map(row => `  ["${row.legacy}", "${row.name}", "${row.tableNameKey ? "enum" : "raw"}"]`).join(",\n");
  return `// Generated by scripts/map-table-namespaces.mjs from docs/schema/table-namespaces.json.
// Frozen history of inherited table names and their vx_ names (docs/0119). Do not edit.
export const LEGACY_TABLE_RENAMES: ReadonlyArray<readonly [legacy: string, current: string, source: "enum" | "raw"]> = [
${pairs}
];
`;
};

if (mode === "--initialize") {
  const models = read(modelsPath);
  const entries = enumEntries(models);
  assert.ok(entries.length > 250 && entries.every(entry => !entry.value.startsWith(`${TABLE_PREFIX}_`)), "TableName is already namespaced; --initialize runs once");
  const legacy = [...entries.map(entry => entry.value), ...RAW_LEGACY_TABLES];
  const { rows, unplaced, collisions, tooLong } = namespaceTables(legacy);
  assert.deepEqual({ unplaced, collisions, tooLong }, { unplaced: [], collisions: [], tooLong: [] }, "Namespace rules are incomplete");
  const byLegacy = new Map(rows.map(row => [row.legacy, row]));
  const keyOf = new Map(entries.map(entry => [entry.value, entry.key]));
  const map = {
    description: "Inherited table name to Vaultix vx_<group>_<entity> name (docs/0119). Frozen history: rows are never removed.",
    prefix: TABLE_PREFIX,
    groups: TABLE_GROUPS,
    tables: rows.map(row => ({ legacy: row.legacy, name: row.name, group: row.group, tableNameKey: keyOf.get(row.legacy) ?? null }))
  };
  writeFileSync(mapPath, JSON.stringify(map, null, 2) + "\n");
  writeFileSync(renamesPath, renderRenames(map.tables));
  const [start, end] = enumRange(models);
  const body = models.slice(start, end).replace(/^(\s+)([A-Za-z0-9]+)\s*=\s*"([^"]+)"/gm, (line, space, key, value) => `${space}${key} = "${byLegacy.get(value).name}"`);
  writeFileSync(modelsPath, models.slice(0, start) + body + models.slice(end));
  console.log(JSON.stringify({ tables: rows.length, tableNameEntries: entries.length, rawTables: RAW_LEGACY_TABLES.length }));
} else if (mode === "--render") {
  // Re-renders the runtime rename list from the frozen map.
  writeFileSync(renamesPath, renderRenames(JSON.parse(read(mapPath)).tables));
  console.log(JSON.stringify({ rendered: renamesPath }));
} else {
  const map = JSON.parse(read(mapPath));
  const { rows, unplaced, collisions, tooLong } = namespaceTables(map.tables.map(table => table.legacy));
  assert.deepEqual({ unplaced, collisions, tooLong }, { unplaced: [], collisions: [], tooLong: [] }, "Namespace rules are incomplete");
  const expected = new Map(rows.map(row => [row.legacy, row.name]));
  for (const table of map.tables) assert.equal(table.name, expected.get(table.legacy), `${table.legacy} no longer follows the namespace rules`);
  const byKey = new Map(map.tables.filter(table => table.tableNameKey).map(table => [table.tableNameKey, table.name]));
  for (const entry of enumEntries(read(modelsPath))) {
    if (byKey.has(entry.key)) assert.equal(entry.value, byKey.get(entry.key), `TableName.${entry.key} must be ${byKey.get(entry.key)}`);
    else assert.ok(entry.value.startsWith(`${TABLE_PREFIX}_`) && Object.keys(TABLE_GROUPS).some(group => entry.value.startsWith(`${TABLE_PREFIX}_${group}_`)), `New TableName.${entry.key} must be vx_<group>_<entity>`);
  }
  assert.equal(read(renamesPath), renderRenames(map.tables), "core/backend/src/db/table-namespaces.ts is stale");
  console.log(JSON.stringify({ tables: map.tables.length, checked: true }));
}
